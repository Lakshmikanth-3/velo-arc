import solc from 'solc';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
const require = createRequire(import.meta.url);
const sources = Object.fromEntries(['ArcVault.sol', 'TestToken.sol'].map(name => [name, { content: readFileSync(resolve('../contracts/arc', name), 'utf8') }]));
export const input = { language: 'Solidity', sources, settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: 'paris', outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object'] } } } };
const output = JSON.parse(solc.compile(JSON.stringify(input), { import: path => { try { return { contents: readFileSync(require.resolve(path), 'utf8') }; } catch { return { error: `Import unavailable: ${path}` }; } } }));
for (const error of output.errors ?? []) { if (error.severity === 'error') throw new Error(error.formattedMessage); }
export const artifacts = Object.fromEntries(['ArcVault', 'ArcVaultFactory', 'MerchantRegistry', 'TestToken', 'MockGatewayWallet'].map(name => {
  const c = output.contracts[name === 'TestToken' || name === 'MockGatewayWallet' ? 'TestToken.sol' : 'ArcVault.sol'][name];
  return [name, { abi: c.abi, bytecode: `0x${c.evm.bytecode.object}`, deployedBytecode: `0x${c.evm.deployedBytecode.object}` }];
}));
mkdirSync('../contracts/arc/artifacts', { recursive: true });
for (const [name, artifact] of Object.entries(artifacts)) writeFileSync(`../contracts/arc/artifacts/${name}.json`, JSON.stringify(artifact, null, 2));
mkdirSync('src/lib/arc', { recursive: true });
writeFileSync('src/lib/arc/abi.ts', '// Generated by pnpm arc:compile.\n' + [['ArcVault', 'vaultAbi'], ['ArcVaultFactory', 'factoryAbi'], ['MerchantRegistry', 'registryAbi']].map(([name, id]) => `export const ${id} = ${JSON.stringify(artifacts[name].abi)} as const;`).join('\n'));
// Include every resolved dependency for standalone explorer standard-JSON verification.
const verificationSources = { ...sources };
for (const path of Object.keys(output.sources)) {
  if (!verificationSources[path]) verificationSources[path] = { content: readFileSync(require.resolve(path), 'utf8') };
}
writeFileSync('../contracts/arc/artifacts/solc-input.json', JSON.stringify({ ...input, sources: verificationSources }, null, 2));
// Keep the SDK package in sync with the app's Arc library.
mkdirSync('../sdk/src', { recursive: true });
for (const f of ['abi.ts', 'config.ts', 'capability.ts']) writeFileSync(`../sdk/src/${f}`, '// Synced from app/src/lib/arc by pnpm arc:compile. Do not edit.\n' + readFileSync(`src/lib/arc/${f}`, 'utf8'));
console.log('Compiled Solidity 0.8.30, optimizer 200, EVM paris; ABI generated.');
